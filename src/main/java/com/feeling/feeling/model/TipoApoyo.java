package com.feeling.feeling.model;

/**
 * Tipos de apoyo académico que un voluntario puede ofrecer
 * y que un estudiante pueda solicitar.
 *
 * @author Isabella Duque
 * @version 1.0
 */
public enum TipoApoyo {

    /**
     * Tutoría general en una materia.
     */
    TUTORIA,

    /** Explicaion de los conceptos o temas de la materia.
     *
     */
    EXPLICACION_CONCEPTOS,

    /** Preparación para exámenes o evaluaciones.
     *
      */
    PREPARACION_EXAMENES,

    /** Ayuda para comprender material de estudio (lecturas, apuntes, guías).
     *
     */
    COMPRENSION_MATERIAL

}
